import assert from 'node:assert/strict';
import { createNativeBoot } from '../src/cabinet/native-boot';
import { createHostBridge } from '../src/cabinet/host-bridge';
const href = 'https://pazneria.github.io/racegpt/?track=technical-bowl&arcadeStart=1&arcadeSession=launch-2&arcadeParentOrigin=https%3A%2F%2Fpazneria.github.io';
let apps = 0, starts = 0; const reports: any[] = [];
const app = {startFromCabinet() { starts++; return true; }};
const bridge = createHostBridge(href, true, {start: () => app.startFromCabinet(), post: (message, origin) => reports.push({message, origin})})!;
const boot = createNativeBoot(() => { apps++; return app; }, {ready: () => bridge.ready()});
assert.equal(boot.boot(href, {deferStart: true}), app);assert.equal(starts, 0, 'No countdown behind token/loading');
assert.equal(reports[0].message.type, 'racegpt:cabinet:ready');assert.equal(reports[0].origin, 'https://pazneria.github.io');
const message = {type: 'racegpt:cabinet:start', version: 1, session: 'launch-2'};
assert.equal(bridge.receive(message, 'https://wrong.example', true), false);
assert.equal(bridge.receive(message, 'https://pazneria.github.io', false), false);
assert.equal(bridge.receive({...message, session: 'stale'}, 'https://pazneria.github.io', true), false);
assert.equal(starts, 0);
assert(bridge.receive(message, 'https://pazneria.github.io', true));assert.equal(starts, 1);assert.equal(bridge.phase, 'started');
bridge.receive(message, 'https://pazneria.github.io', true);assert.equal(starts, 1, 'A repeated start cannot restart countdown');
assert.equal(reports.at(-1).message.type, 'racegpt:cabinet:started');
bridge.back();assert.equal(reports.at(-1).message.type, 'racegpt:cabinet:back');
boot.boot(href, {deferStart: true});assert.equal(apps, 1);
assert.equal(createHostBridge(href, false, {start: () => true, post() {}}), null);
const regular = createNativeBoot(() => app);regular.boot('https://pazneria.github.io/racegpt/?track=test-track-b');assert.equal(starts, 1, 'Standalone menu preserved');
const topLevel = createNativeBoot(() => app);topLevel.boot(href);assert.equal(starts, 2, 'Explicit full-page arcade start remains available');
let failures = 0; const broken = createNativeBoot(() => { failures++; throw new Error('engine failed'); });
assert.throws(() => broken.boot(href));assert.throws(() => broken.boot(href));assert.equal(failures, 1);
const failure = createHostBridge(href, true, {start() { throw new Error('start failed'); }, post: message => reports.push({message})})!;
failure.ready();failure.receive(message, 'https://pazneria.github.io', true);assert.equal(failure.phase, 'error');assert.equal(reports.at(-1).message.type, 'racegpt:cabinet:error');
console.log('PASS native cabinet bridge: selected-track identity, deferred countdown, one app/start, source/origin/session rejection, errors and standalone menu');
