import assert from 'node:assert/strict';
import { createNativeBoot } from '../optional/native-boot';
let instances=0, starts=0, reports:any[]=[];
const app={startFromCabinet:()=>{starts++;return true;}};
const bridge=createNativeBoot(()=>{instances++;return app;},{ready:d=>reports.push(d)});
assert.equal(bridge.boot('https://example.test/racegpt/?track=technical-bowl&arcadeStart=1'),app);
assert.equal(bridge.boot('https://example.test/racegpt/?track=technical-bowl&arcadeStart=1'),app);
assert.equal(instances,1);assert.equal(starts,1);assert.equal(reports.length,1);
assert.deepEqual(reports[0],{autoStarted:true,trackId:'technical-bowl'});
assert.ok(Object.isFrozen(reports[0]));
const regular=createNativeBoot(()=>app,{ready:d=>reports.push(d)});
regular.boot('https://example.test/racegpt/?track=test-track-b');assert.equal(starts,1);
assert.equal(reports.at(-1).autoStarted,false);
let failures=0,errors=0;
const broken=createNativeBoot(()=>{failures++;throw new Error('renderer failed');},{error:()=>errors++});
assert.throws(()=>broken.boot('https://example.test/racegpt/?arcadeStart=1'));
assert.throws(()=>broken.boot('https://example.test/racegpt/?arcadeStart=1'));
assert.equal(failures,1);assert.equal(errors,1);
console.log('PASS optional native boot: one app, one opt-in start, ordinary menu preserved, immutable ready detail, failure latched');
